const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const filename = require('node:path').resolve('lib/operacional/project-labels.ts');
const mod = new Module(filename, module); mod.filename = filename; mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions: {target: ts.ScriptTarget.ES2017, module: ts.ModuleKind.CommonJS}}).outputText, filename);
const { fixtureTitle, displayProjectLabel, resolveProject } = mod.exports;
const projects = [{ code: '020', name: 'Hero Cap', label: '020.Hero Cap' }, {code: 'E033', name: 'Sport Care Blister Packaging', label: 'E033.Sport Care Blister Packaging'}, {code: 'OTRO', name: 'Otro', label: 'Otro'}, {code: '036', name: 'Scalp Clip gun', label: '036.Scalp Clip gun'}, {code: 'E036', name: 'OsteoOne', label: 'E036.OsteoOne'}];
assert.equal(fixtureTitle('020.Hero Cap', ' hola ', projects), 'FXT. 020. hola');
assert.equal(fixtureTitle('E020.Hero Cap', 'hola', projects), 'FXT. 020. hola');
assert.equal(displayProjectLabel('E020.Hero Cap', projects), '020.Hero Cap');
assert.equal(fixtureTitle('E033.Sport Care Blister Packaging', 'Seal Fixture', projects), 'FXT. E033. Seal Fixture');
assert.equal(fixtureTitle('Otro', 'Tipping die', projects), 'FXT. Otro. Tipping die');
assert.equal(fixtureTitle('013.T-EZ', 'Prueba a 20°', projects), 'FXT. 013. Prueba a 20°');
assert.equal(fixtureTitle('020.Hero Cap', ' ', projects), '');
assert.equal(resolveProject('E036.OsteoOne', projects).code, 'E036');
assert.equal(resolveProject('036.Scalp Clip gun', projects).code, '036');
assert.equal(displayProjectLabel('E020.Other project', projects), 'E020.Other project');
assert.equal(displayProjectLabel('E020.Hero Cap', [...projects, {code: 'E020', name: 'Hero Cap', label: 'E020.Hero Cap'}]), 'E020.Hero Cap');
console.log('Project labels: fixture titles, historical Hero Cap, real E codes, unknown projects and exact catalog precedence passed.');
