const fs = require('node:fs'), ts = require('typescript'), assert = require('node:assert/strict');
const m = { exports: {} };
new Function('require', 'module', 'exports', ts.transpileModule(fs.readFileSync('lib/inventario/voucher-numbering.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText)(require, m, m.exports);
const { voucherWeek, voucherPrefix, sequenceLetters, numberingSuggestions, confirmNumbering } = m.exports;
assert.deepEqual(voucherWeek('2026-10-29T18:00:00Z'), { year: 2026, week: 44, key: '2026-44' });
assert.equal(voucherPrefix('B1', '2026-10-30T18:00:00Z'), 'VL.B1.4426-');
assert.equal(voucherPrefix('B2', '2026-11-02T05:59:59Z'), 'VL.B2.4426-', 'Sunday night in Monterrey');
assert.equal(voucherPrefix('B2', '2026-11-02T06:00:00Z'), 'VL.B2.4526-', 'Monday midnight in Monterrey');
assert.equal(voucherPrefix('B1', '2027-01-01T18:00:00Z'), 'VL.B1.5326-', 'ISO week-year remains 2026');
assert.equal(voucherPrefix('B1', '2027-01-04T18:00:00Z'), 'VL.B1.0127-');
assert.equal(sequenceLetters(1), 'A'); assert.equal(sequenceLetters(26), 'Z'); assert.equal(sequenceLetters(27), 'AA'); assert.equal(sequenceLetters(52), 'AZ'); assert.equal(sequenceLetters(53), 'BA'); assert.equal(sequenceLetters(703), 'AAA');
let ledger = { prefix: 'VL.B1.4426-', entries: [{ id: 'first' }, { id: 'second' }, { id: 'third' }] };
assert.deepEqual(numberingSuggestions(ledger), { first: 'VL.B1.4426-A', second: 'VL.B1.4426-B', third: 'VL.B1.4426-C' });
confirmNumbering(ledger, 'first', 'VL.B1.4426-A', 'VL.B1.4426-A');
ledger.entries[1].excluded = true;
assert.deepEqual(numberingSuggestions(ledger), { third: 'VL.B1.4426-B' });
assert.throws(() => confirmNumbering(ledger, 'third', 'VL.B1.4426-C', 'VL.B1.4426-C'), /sugerencia cambió/);
assert.throws(() => confirmNumbering(ledger, 'third', 'VL.B1.4426-A', 'VL.B1.4426-B'), /otro vale/);
assert.throws(() => confirmNumbering(ledger, 'third', 'VL.B2.4426-B', 'VL.B1.4426-B'), /formato/);
confirmNumbering(ledger, 'third', 'VL.B1.4426-B', 'VL.B1.4426-B');
assert.throws(() => confirmNumbering(ledger, 'first', 'VL.B1.4426-D', ''), /estado/);
ledger = { prefix: 'VL.B1.4426-', entries: [{ id: 'old', confirmedTitle: 'VL.B1.4426-Z' }, { id: 'new' }] };
assert.equal(numberingSuggestions(ledger).new, 'VL.B1.4426-AA');
ledger = { prefix: 'VL.B1.4426-', entries: [{ id: 'a' }, { id: 'b', confirmedTitle: 'VL.B1.4426-B' }, { id: 'c' }] };
ledger.entries[0].excluded = true;
assert.equal(numberingSuggestions(ledger).c, 'VL.B1.4426-C', 'Never renumber a confirmed ID or backfill before it');
console.log('Weekly numbering: Monterrey midnight, Monday, week-year, 53 weeks, B1/B2, Z/AA, exclusions, confirmed IDs and stale/duplicate confirmations passed.');
